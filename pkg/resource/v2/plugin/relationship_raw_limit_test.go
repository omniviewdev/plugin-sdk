package plugin

import (
	"context"
	"fmt"
	"testing"

	resourcev2 "github.com/omniviewdev/plugin-sdk/pkg/resource/v2"
	resourcepb "github.com/omniviewdev/plugin-sdk/proto/resource/v2"
	"google.golang.org/grpc"
	"google.golang.org/protobuf/proto"
)

func TestActualRawGRPCRelationshipTargetLimitBeforeDecode(t *testing.T) {
	for _, count := range []int{resourcev2.MaxRelationshipTargets, resourcev2.MaxRelationshipTargets + 1} {
		t.Run(fmt.Sprint(count), func(t *testing.T) {
			p := &relationshipBoundaryProvider{}
			server := grpc.NewServer()
			RegisterServer(server, p)
			request, err := resourcev2.ToProtoRelationshipResolutionRequest(relationshipFixtureRequest())
			if err != nil {
				t.Fatal(err)
			}
			first := request.Targets[0]
			for i := 1; i < count; i++ {
				target := proto.Clone(first).(*resourcepb.ReadTarget)
				target.Type = fmt.Sprintf("opaque/other-linked-type/%d", i)
				request.Targets = append(request.Targets, target)
			}
			// Bypass the handwritten client's semantic admission. These generated bytes
			// reach the actual gRPC default-proto decoder, including the hostile 257th
			// otherwise-valid binding. The raw field counter must reject it first.
			wireRequest := &resourcepb.AncillaryRequest{Version: 2, Operation: "resolveRelationships", RelationshipResolution: request}
			var response resourcepb.AncillaryResponse
			err = pipe(t, server).Invoke(context.Background(), resourcepb.ResourceAncillary_Call_FullMethodName, wireRequest, &response)
			if count == resourcev2.MaxRelationshipTargets {
				if err != nil || p.calls.Load() != 1 {
					t.Fatalf("valid boundary rejected: calls=%d err=%v", p.calls.Load(), err)
				}
			} else if resourcev2.ErrorCode(domainError(err)) != "RESOURCE_LIMIT" || p.calls.Load() != 0 {
				t.Fatalf("raw target cap lost before dispatch: calls=%d err=%v", p.calls.Load(), err)
			}
		})
	}
}
